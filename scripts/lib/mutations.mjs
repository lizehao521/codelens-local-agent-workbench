/**
 * 变异体表 —— 逐题把实现改坏，对应判据必须变红。
 *
 * 与 mutation-probe.mjs 分开的理由：表是数据、runner 是机制，两者演进节奏不同
 * （每采纳一题就加一行，而 runner 的安全约束不该跟着动），且各自都要守住 ≤300 行。
 *
 * 字段：
 *   id       变异体标识
 *   task     它守的是 self-upgrade/tasks.json 里哪道题（覆盖率按此去重统计）
 *   file     靶子路径，相对 fileRoot
 *   fileRoot 靶子所在根：server / client / repo（缺省 = pkg）
 *   pkg      判据在哪个包跑：server / client（缺省 server）——决定 vitest 的 cwd
 *   from/to  源串与替换串。from 必须在文件里恰好出现 hits 次（缺省 1）
 *   test     判据路径，相对 pkg
 *   why      改坏之后为什么判据必须红
 *
 * 选源串的三条约束（踩过的坑写在这里）：
 *   1. 不跨行。受保护件在 Windows 检出是 CRLF，跨行串会因行尾差异匹配不上。
 *   2. 不选「改坏即死循环」的点。fs.replace 的空 oldText 守卫一旦短路，
 *      indexOf 永远不前进，判据会挂到超时——那测的是超时不是判别力。
 *   3. 不选格式化/注释。改坏必须落在行为上，否则判据绿得理所当然。
 */

